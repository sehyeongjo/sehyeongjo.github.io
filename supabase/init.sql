-- Left column of the page: name, image, shortcontact (markdown).
create table contents (
  id text primary key,
  content text not null default ''
);

-- Sections of the page body, rendered as "## title" followed by its items.
create table sections (
  id text primary key,
  title text not null,
  position int not null,                 -- smaller first; id 'publications' shows the publications table
  is_list boolean not null default true  -- false: items render as plain paragraphs instead of bullets
);

create table section_items (
  id bigint generated by default as identity primary key,
  section_id text not null references sections (id) on update cascade on delete cascade,
  content text not null default '',  -- markdown of one bullet; extra lines continue it (indent '- ' for sub-bullets)
  position int not null               -- smaller first within the section
);

create table publications (
  id bigint generated by default as identity primary key,  -- higher id shows first
  title text not null default '',
  authors text not null default '',
  booktitle text not null default '',
  short_booktitle text not null default '',
  links text not null default '',
  thumbnail text not null default ''
);

-- Public bucket for images; publications.thumbnail and contents 'image' hold the file name.
-- Upload files in Dashboard > Storage (they are not part of this SQL).
insert into storage.buckets (id, name, public) values ('thumbnails', 'thumbnails', true);

-- Site uses the publishable (anon) key: read-only for everyone, no writes.
alter table contents enable row level security;
alter table sections enable row level security;
alter table section_items enable row level security;
alter table publications enable row level security;
create policy "public read" on contents for select to anon using (true);
create policy "public read" on sections for select to anon using (true);
create policy "public read" on section_items for select to anon using (true);
create policy "public read" on publications for select to anon using (true);
grant select on contents, sections, section_items, publications to anon;

